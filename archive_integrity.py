"""Read-only evidence of completeness for each Vladivostok calendar day.

The source sometimes omits a round-end timestamp. Merely receiving a round
later is NOT proof of the day on which it ended. Never label such a day as
verified. This module does not change DEMO, archive, or legacy counters.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

from coefficient_stats import event_time
from round_archive import STREAM_KEY

TZ = ZoneInfo("Asia/Vladivostok")
MAX_DAY_EVENTS = 20000


async def archive_day_evidence(redis, day: str, *, legacy_total=None):
    """Summarize append-only stream evidence without claiming impossible certainty."""
    if not all(hasattr(redis, action) for action in ("xrange", "xrevrange")):
        # A degraded Redis adapter must never crash the history page or
        # cause a legacy counter to masquerade as verified.
        return {
            "day": day, "status": "unverified",
            "archived_rounds": None,
            "legacy_total": int(legacy_total) if legacy_total is not None else None,
            "counts_match": None, "reasons": ["проверка архива недоступна"],
        }
    start = datetime.strptime(day, "%Y-%m-%d").replace(tzinfo=TZ)
    end = start + timedelta(days=1)
    first_ms = int(start.timestamp() * 1000)
    end_ms = int(end.timestamp() * 1000)
    # Stream IDs are generated by Redis at insertion time, not a game clock.
    before = await redis.xrevrange(
        STREAM_KEY, min="-", max=f"({first_ms}-0", count=1,
    )
    events = await redis.xrange(
        STREAM_KEY, min=f"{first_ms}-0",
        max=f"{end_ms-1}-999999999", count=MAX_DAY_EVENTS + 1,
    )
    after = await redis.xrange(
        STREAM_KEY, min=f"{end_ms}-0", max="+", count=1,
    )
    truncated = len(events) > MAX_DAY_EVENTS
    if truncated:
        events = events[:MAX_DAY_EVENTS]
    rounds = 0
    baselines = 0
    gaps = 0
    missing_source_time = 0
    timestamp_mismatches = 0
    first_event_at = None
    last_event_at = None
    for stream_id, fields in events:
        observed = fields.get("observed_at")
        if observed:
            try:
                stamp = datetime.fromtimestamp(int(observed)/1000, timezone.utc)
            except (ValueError, TypeError, OverflowError, OSError):
                stamp = None
        else:
            stamp = None
        if stamp is not None:
            as_iso = stamp.astimezone(TZ).isoformat()
            first_event_at = first_event_at or as_iso
            last_event_at = as_iso

        kind = fields.get("type")
        if kind == "gap":
            gaps += 1
        elif kind == "baseline":
            baselines += 1
        elif kind == "round":
            rounds += 1
            source_time = fields.get("source_time")
            parsed = event_time({"timestamp": source_time}) if source_time else None
            if parsed is None:
                missing_source_time += 1
            elif parsed.date() != start.date():
                timestamp_mismatches += 1

    archive_started_before = bool(before)
    archive_continued_after = bool(after)
    finished_day = end <= datetime.now(TZ)
    observed_whole_day = (
        archive_started_before and archive_continued_after and finished_day
        and not baselines and not gaps and not truncated
    )
    compares = legacy_total is not None
    counters_match = compares and int(legacy_total) == rounds
    # Only an exact timestamp match, no archive gaps, and a day that began
    # and ended while the archive was running can support day-level fidelity.
    # This does NOT independently prove the third-party game was complete.
    sequence_checked = (
        observed_whole_day and rounds > 0 and timestamp_mismatches == 0
        and compares and counters_match
    )
    verified = sequence_checked and missing_source_time == 0
    reasons = []
    if not archive_started_before:
        reasons.append("архив ещё не охватывал начало суток")
    if not archive_continued_after:
        reasons.append("архив не подтверждает окончание суток")
    if baselines:
        reasons.append("сбор начался или был переинициализирован внутри суток")
    if gaps:
        reasons.append("обнаружены пропущенные участки истории")
    if missing_source_time:
        reasons.append("источник не сообщил точное время части раундов")
    if timestamp_mismatches:
        reasons.append("некоторые результаты относятся к другим суткам")
    if truncated:
        reasons.append("слишком много записей для полной проверки")
    if compares and not counters_match and observed_whole_day:
        reasons.append("итоговые счётчики не совпадают с архивом")
    if not finished_day:
        reasons.append("текущие сутки ещё не закончились")
    return {
        "day": day,
        "status": (
            "verified" if verified
            else "sequence_checked" if sequence_checked
            else "unverified"
        ),
        "archived_rounds": rounds,
        "legacy_total": int(legacy_total) if compares else None,
        "counts_match": counters_match if compares else None,
        "archive_started_before_day": archive_started_before,
        "archive_continued_after_day": archive_continued_after,
        "source_time_missing": missing_source_time,
        "cross_day_timestamp_mismatches": timestamp_mismatches,
        "gaps": gaps,
        "baselines": baselines,
        "truncated": truncated,
        "first_seen_at": first_event_at,
        "last_seen_at": last_event_at,
        "reasons": reasons,
    }
